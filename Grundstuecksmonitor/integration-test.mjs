import assert from 'node:assert/strict';
import {mkdtemp,readFile,writeFile,readdir,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {createHash} from 'node:crypto';
import {FileBlob,SpreadsheetFile,Workbook} from '@oai/artifact-tool';
const execute=promisify(execFile);
const root=await mkdtemp(join(tmpdir(),'plot-monitor-integration-'));
const headers=['Postleitzahl','Ort','Straße','Größe (m²)','Preis (€)','Quelle','Inseratslink','Erstmals gefunden','Zuletzt geprüft','Status','Exposé-Dateiname','Interne ID','Anbieter'];
const wb=Workbook.create();
const put=(name,rows)=>{const s=wb.worksheets.add(name);s.getRangeByIndexes(0,0,rows.length,rows[0].length).values=rows;return s;};
put('Grundstücke',[headers,['10000','Musterstadt','Altweg 5',700,280000,'Musterquelle','https://example.test/offer/old',new Date('2026-08-01'),new Date('2026-08-01'),'Neu','','old','Muster Immobilien GmbH']]);
const area=Array.from({length:50},(_,i)=>[String(10000+i),'Mustergebiet','','Ja']);
put('Suchgebiet',[['Postleitzahl','Region','Quelldatei','Aktiv'],...area]);
put('Quellen',[['Quelle','Typ','Start-/Alarm-URL','Zulässiger Zugriff','Aktiv','Letzte Prüfung','Status / Hinweis'],['Musterquelle','Makler','https://example.test','Detailseite','Ja','','']]);
put('Hausbaufirmen',[['Name/Firma','Aktiv'],['Muster Fertighaus','Ja']]);
put('Regeln',[['Bereich','Festlegung'],['Manuelle Regel','Unverändert erhalten']]);
put('Adressrecherche',[['ID','Notiz'],['legacy','Manuelle Notiz erhalten']]);
put('PLZ-Angebote',[['Titel','','','','','','','','',''],['Hinweis','','','','','','','','',''],['PLZ mit Angebot','Recherchebedarf',50,0,'','','','','',''],['Postleitzahl','Region','Angebot','Größe','Preis','Quelle','Link','Auswahl','Status','Hinweis']]);
put('Müssen geprüft werden',[[...headers,'Prüfgrund','Ursprungszeile'],['10000','Musterstadt','',700,280000,'Musterquelle','https://example.test/offer/review',new Date('2026-08-01'),new Date('2026-08-01'),'Vorhanden','','legacy','Muster Immobilien GmbH','Adresse nicht öffentlich angegeben',2]]);
const path=join(root,'KI_Grundstuecke.xlsx');
await (await SpreadsheetFile.exportXlsx(wb)).save(path);
const now=new Date().toISOString();
const offer={postalCode:'10000',city:'Musterstadt',street:'Neuweg 12',sizeSqm:700,priceEur:280000,source:'Musterquelle',listingUrl:'https://example.test/offer/new',internalId:'new',available:true,
  checkedAt:now,evidenceUrl:'https://example.test/offer/new',availabilityEvidence:'Wohnbaugrundstück ist verfügbar',providerName:'Muster Immobilien GmbH',providerEvidenceUrl:'https://example.test/impressum',offerType:'residential_plot',brwEurPerSqm:300,brwEvidenceUrl:'https://example.test/brw',locationType:'urban',buildabilityBasis:'b_plan',buildabilityEvidenceUrl:'https://example.test/b-plan'};
const payload={sourceChecks:[{name:'Musterquelle',status:'ok',checkedAt:now,method:'detail_pages',note:'Synthetische Integrationsprüfung',evidenceUrls:[offer.listingUrl]}],offers:[{...offer,internalId:'legacy',listingUrl:'https://example.test/offer/review',evidenceUrl:'https://example.test/offer/review',street:'',available:false,availabilityState:'removed',availabilityEvidence:'Angebot wurde deaktiviert'},offer,{...offer,internalId:'missing',listingUrl:'https://example.test/offer/missing',street:'',evidenceUrl:'https://example.test/offer/missing'}]};
const input=join(root,'run.json');await writeFile(input,JSON.stringify(payload));
const command=fileURLToPath(new URL('./monitor.mjs',import.meta.url));
const run=async extra=>execute(process.execPath,[command,'--target-dir',root,'--input',input,...extra],{maxBuffer:1024*1024});
const hash=async()=>createHash('sha256').update(await readFile(path)).digest('hex');
try {
  const before=await hash();
  await run(['--dry-run']);
  assert.equal(await hash(),before);assert.ok(!(await readdir(root)).includes('Logs'));
  await run([]);
  let saved=await SpreadsheetFile.importXlsx(await FileBlob.load(path));
  const rows=saved.worksheets.getItem('Grundstücke').getUsedRange().values.filter(r=>r[0]);
  assert.equal(rows.length,3);assert.equal(rows.filter(r=>r[11]==='new').length,1);
  assert.equal(rows.find(r=>r[11]==='old')[9],'Vorhanden');
  assert.equal(rows.find(r=>r[11]==='old')[rows[0].indexOf('Aktualität')],'Veraltet – erneut prüfen');
  const review=saved.worksheets.getItem('Müssen geprüft werden').getUsedRange().values.filter(r=>r[0]);
  assert.equal(review.length,3);assert.match(String(review[1][review[0].indexOf('Nächster Schritt')]),/Abgeschlossen/);
  assert.equal(rows.some(r=>r[11]==='legacy'),false);
  assert.equal(saved.worksheets.getItem('Regeln').getRange('B2').values[0][0],'Unverändert erhalten');
  assert.equal(saved.worksheets.getItem('Adressrecherche').getRange('B2').values[0][0],'Manuelle Notiz erhalten');
  assert.equal(saved.worksheets.getItem('PLZ-Angebote').getRange('C3').values[0][0],1);
  await run([]);
  saved=await SpreadsheetFile.importXlsx(await FileBlob.load(path));
  assert.equal(saved.worksheets.getItem('Grundstücke').getUsedRange().values.filter(r=>r[11]==='new').length,1);
  assert.equal(saved.worksheets.getItem('Müssen geprüft werden').getUsedRange().values.filter(r=>r[11]==='missing').length,1);
  assert.equal((await readdir(join(root,'Backups'))).length,2);
  console.log(JSON.stringify({passed:true,checks:['read-only simulation','accepted import','review routing','stale status','manual notes preserved','coverage view','repeat without duplicates','distinct backups']}));
} finally {await rm(root,{recursive:true,force:true});}
